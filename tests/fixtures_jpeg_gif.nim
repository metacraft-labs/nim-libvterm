## Generation recipe (one-shot, for posterity):
##
##   nix-shell -p imagemagick
##   # 8x8 solid red JPEG (lossy; quantised to ~0xFE,0,0).
##   magick -size 8x8 xc:'rgb(255,0,0)' -quality 95 jpeg:solid_red.jpg
##   # 4x4 solid red GIF (palette of one colour; lossless).
##   magick -size 4x4 xc:red gif:solid_red.gif
##   # 2x2 4-colour GIF: TL red, TR green(0,128,0), BL blue, BR white.
##   magick -size 2x2 xc:red \
##     -fill green -draw 'point 1,0' \
##     -fill blue  -draw 'point 0,1' \
##     -fill white -draw 'point 1,1' \
##     -compress none gif:colors2x2.gif
##   # 2x2 4-colour JPEG (lossy; per-pixel R/G/B drift up to a few units).
##   magick -size 2x2 xc:red \
